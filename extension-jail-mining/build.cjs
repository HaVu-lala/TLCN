const fs = require('node:fs');
const root = 'D:/Tools/game-tools-extension';
let code = fs.readFileSync(root + '/game-tools.js', 'utf8');
const old = fs.readFileSync(root + '/backup-before-upgrade-timing-20261025-005524/game-tools.js', 'utf8');
const a = '// ===================== Đập đồ (trước đây: upgrade.js) =====================';
const b = '// ===================== Đi tới map';
const start = code.indexOf(a), end = code.indexOf(b, start);
const oa = old.indexOf(a), ob = old.indexOf(b, oa);
if ([start, end, oa, ob].some(x => x < 0)) throw Error('Cannot restore upgrade section');
code = code.slice(0, start) + old.slice(oa, ob) + code.slice(end);
const group = "    { id: 'items', icon: '🎒', label: 'Đồ đạc', re: /Vứt|Đập/i },";
if (!code.includes(group)) throw Error('Hub group missing');
code = code.replace(group, "    { id: 'jail', icon: '⛏', label: 'Đập đá trong tù', re: /Đập đá trong tù/i },\n" + group);
fs.writeFileSync(__dirname + '/game-tools.js', code);
const manifest = JSON.parse(fs.readFileSync(root + '/manifest.json', 'utf8'));
manifest.version = '2.6.0.2';
manifest.content_scripts[0].js = ['game-tools.js', 'jail-mining.js'];
fs.writeFileSync(__dirname + '/manifest.json', JSON.stringify(manifest, null, 2));
console.log('Built separate jail mining tab; original gear upgrade restored');
